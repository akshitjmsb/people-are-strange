// Generate supabase/seed.sql from lib/seed-data.ts.
// Reads the seed POIs, computes H3 indexes (res 7 + 9) with h3-js, and emits
// INSERT statements. Run: npm run seed:sql
import { readFileSync, writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import { dirname, join } from 'node:path';
import { latLngToCell } from 'h3-js';

const __dirname = dirname(fileURLToPath(import.meta.url));
const root = join(__dirname, '..');

// The seed file is plain data — extract the array literal and eval it as JS.
const ts = readFileSync(join(root, 'lib/seed-data.ts'), 'utf8');
const start = ts.indexOf('[', ts.indexOf('SEED_POIS'));
const end = ts.lastIndexOf(']');
if (start === -1 || end === -1) {
  throw new Error('Could not locate SEED_POIS array in lib/seed-data.ts');
}
const arrayLiteral = ts.slice(start, end + 1);
// eslint-disable-next-line no-eval
const seeds = eval(`(${arrayLiteral})`);

const esc = (v) => (v == null ? 'null' : `'${String(v).replace(/'/g, "''")}'`);
const escArray = (arr) =>
  arr && arr.length
    ? `array[${arr.map((t) => esc(t)).join(',')}]::text[]`
    : 'null';

const rows = seeds.map((p) => {
  const h9 = latLngToCell(p.lat, p.lng, 9);
  const h7 = latLngToCell(p.lat, p.lng, 7);
  return `  (${esc(p.name)}, ${esc(p.category)}::poi_category, ${esc(p.subcategory)}, ${esc(p.description)}, ${p.lat}, ${p.lng}, ${esc(h9)}, ${esc(h7)}, ${esc(p.address)}, ${escArray(p.tags)}, ${esc(p.source)})`;
});

const sql = `-- Auto-generated by scripts/generate-seed-sql.mjs — do not edit by hand.
-- ${seeds.length} Montreal POIs with precomputed H3 indexes.
-- Apply after 0001_init.sql once the Supabase project is restored.

insert into pois (name, category, subcategory, description, lat, lng, h3_res9, h3_res7, address, tags, source) values
${rows.join(',\n')};

-- Refresh the hex summary materialized views.
select refresh_hex_summaries();
`;

writeFileSync(join(root, 'supabase/seed.sql'), sql);
console.log(`Wrote supabase/seed.sql with ${seeds.length} POIs.`);
